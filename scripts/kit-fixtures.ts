#!/usr/bin/env node
/**
 * kit-fixtures: the recorded Claude Code fixtures as a module the test kit can load. A kit test imports code only (no
 * JSON, no file reads), so test/support/kit-fixtures.ts holds every fixture of test/fixtures/cc/<probed>/, and its
 * `kitReader` feeds test/support/fixtures.ts's typed loaders, which check each shape as they do under node.
 *
 *   node scripts/kit-fixtures.ts            write kit-fixtures.ts
 *   node scripts/kit-fixtures.ts --check    exit 1 when kit-fixtures.ts is not what the JSON files give
 */
import fs from 'node:fs';
import path from 'node:path';
import { PLUGIN } from './lib/paths.ts';
import { probedVersion } from './lib/claude-bin.ts';

export const fixtureDir = (version: string = probedVersion()): string => path.join(PLUGIN, 'test', 'fixtures', 'cc', version);
export const KIT_FILE: string = path.join(PLUGIN, 'test', 'support', 'kit-fixtures.ts');

/** kit-fixtures.ts's text for the fixtures in `dir`: each file's parsed JSON under its name, in name order. */
export function kitText(dir: string): string {
  const names = fs.readdirSync(dir).filter(f => f.endsWith('.json')).sort();
  const body = names.map(f => `  ${JSON.stringify(f.slice(0, -5))}: ${JSON.stringify(JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')))},`);
  return [
    '// Generated by scripts/kit-fixtures.ts from test/fixtures/cc/; do not edit. npm run test:scripts checks it.',
    "import type { Reader } from './fixtures.js'",
    '',
    'const FIXTURES: Readonly<Record<string, unknown>> = {',
    ...body,
    '}',
    '',
    '/** The loaders\' reader in the kit: a fixture\'s text by name. */',
    'export const kitReader: Reader = name => {',
    '  if (!Object.hasOwn(FIXTURES, name)) throw new Error(`no fixture ${name}`)',
    '  return JSON.stringify(FIXTURES[name])',
    '}',
    '',
  ].join('\n');
}

function main(): number {
  const dir = fixtureDir();
  const want = kitText(dir);
  if (!process.argv.includes('--check')) { fs.writeFileSync(KIT_FILE, want); return 0; }
  const have = fs.existsSync(KIT_FILE) ? fs.readFileSync(KIT_FILE, 'utf8') : '';
  if (have === want) return 0;
  process.stderr.write(`kit-fixtures: ${path.relative(process.cwd(), KIT_FILE)} is out of date; run node scripts/kit-fixtures.ts\n`);
  return 1;
}

if (import.meta.main) process.exitCode = main();
